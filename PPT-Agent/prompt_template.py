"""PPT-Agent 的专用系统提示模板。

与原始 agent 的差异说明
----------------------
原实现用 ``string.Template`` + ``$var`` 占位符。**这里刻意改用 ``{{VAR}}`` +
``str.replace``**，原因是 ppt-master skill 的文档里大量出现 ``${SKILL_DIR}``
这种字面量；若继续用 ``Template.substitute``，必须把 skill 文本里的每一个
``$`` 都转义成 ``$$``，极易出错且生成的提示词可读性差。

占位符清单（全部由 agent.py 的 build_system_prompt() 填充）：
    {{SKILL_DIR}}           ppt-master skill 根目录的绝对路径
    {{OUTPUT_ROOT}}         生成项目的落盘根目录
    {{OPERATING_SYSTEM}}    操作系统名
    {{PYTHON_CMD}}          本机可用的 Python 命令（Windows 为 python）
    {{PROFILE_NAME}}        当前运行 profile（quick / default）
    {{PROFILE_DISCIPLINE}}  该 profile 的交互纪律
    {{TOOL_LIST}}           由 inspect 自动生成的工具清单
    {{SKILL_PRELOAD}}       预载入的 skill 权威文档全文
    {{OUTPUT_ROOT_LISTING}} 输出根目录当前内容
"""

